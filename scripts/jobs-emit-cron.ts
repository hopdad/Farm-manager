/**
 * pnpm jobs:emit-cron: src/jobs/registry.ts -> db/supabase/cron.sql (plan §1 "Scheduled
 * functions"; docs/contracts.md §5). The production clock (Supabase Cron: pg_cron + pg_net)
 * then POSTs each job exactly like tools/clock does locally.
 *
 *   pnpm jobs:emit-cron            write db/supabase/cron.sql
 *   pnpm jobs:emit-cron --check    exit 1 if the file is missing or out of date (CI)
 *   pnpm jobs:emit-cron --stdout   print instead of writing
 *
 * - validateRegistry (the same validator as the clock); host 'pc' jobs are skipped.
 * - One named cron.schedule per job (re-applying updates it in place), whose command is
 *   net.http_post(<base>/api/jobs/<name>, bearer header, timeout_milliseconds := 5000).
 * - JOBS_SECRET is never written: the command reads the base URL and the secret from Vault at
 *   run time (`farm_jobs_base_url`, `farm_jobs_secret`).
 * - Jobs that left the registry are unscheduled (only ones whose command posts to /api/jobs/).
 * Output is deterministic (no timestamps), so --check can compare it.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { toPgCronSchedule, type ValidJob, validateRegistry } from '../src/jobs/schedule';
import { isMainModule } from '../src/lib/proc';

export const CRON_SQL_FILE = path.join('db', 'supabase', 'cron.sql');
export const VAULT_BASE_URL = 'farm_jobs_base_url';
export const VAULT_SECRET = 'farm_jobs_secret';
export const HTTP_TIMEOUT_MS = 5_000;

const quote = (s: string) => `'${s.replace(/'/g, "''")}'`;
const vault = (name: string) =>
  `(select decrypted_secret from vault.decrypted_secrets where name = ${quote(name)})`;

/** The SQL command pg_cron runs for one job (a single net.http_post). */
export function jobCommand(name: string): string {
  return [
    'select net.http_post(',
    `    url := ${vault(VAULT_BASE_URL)} || ${quote(`/api/jobs/${name}`)},`,
    '    headers := jsonb_build_object(',
    "      'Content-Type', 'application/json',",
    `      'Authorization', 'Bearer ' || ${vault(VAULT_SECRET)}`,
    '    ),',
    "    body := '{}'::jsonb,",
    `    timeout_milliseconds := ${HTTP_TIMEOUT_MS}`,
    '  )',
  ].join('\n');
}

/** Jobs that pg_cron should schedule: every valid job not meant for the shop PC. */
export function cronJobs(valid: ValidJob[]): ValidJob[] {
  return valid.filter((j) => j.host !== 'pc');
}

export function emitCronSql(valid: ValidJob[]): string {
  const jobs = cronJobs(valid);
  const skipped = valid.filter((j) => j.host === 'pc').map((j) => j.name);
  const out: string[] = [
    '-- db/supabase/cron.sql: GENERATED by `pnpm jobs:emit-cron` from src/jobs/registry.ts. Do not edit.',
    '--',
    '-- Supabase Cron (pg_cron + pg_net) POSTs each job to <base>/api/jobs/<name> with the bearer',
    '-- secret, like tools/clock does locally. Apply it in the `postgres` database (db:configure prod',
    '-- at milestone MD, or locally to rehearse CLOCK=pgcron). Schedules are UTC.',
    '--',
    '-- The commands read two Vault secrets at run time (never stored in this file):',
    `--   select vault.create_secret('https://<production domain>', '${VAULT_BASE_URL}');`,
    `--   select vault.create_secret('<JOBS_SECRET>', '${VAULT_SECRET}');`,
    '-- Locally (CLOCK=pgcron) the base URL is http://host.docker.internal:3000.',
    '-- Re-applying is safe: cron.schedule(<name>, ...) replaces the job of that name.',
    skipped.length
      ? `-- Not scheduled here (host 'pc', the shop PC's clock runs them): ${skipped.join(', ')}.`
      : "-- No host 'pc' jobs.",
    '',
  ];
  if (!jobs.length) out.push('-- (no app jobs registered yet)', '');
  for (const j of jobs) {
    out.push(
      `-- ${j.name}: ${j.schedule.kind === 'every' ? `every ${j.schedule.seconds} seconds` : `cron ${j.schedule.expr} (UTC)`}, budget ${j.budgetMs} ms`,
      'select cron.schedule(',
      `  ${quote(j.name)},`,
      `  ${quote(toPgCronSchedule(j.schedule))},`,
      `  $job$${jobCommand(j.name)}$job$`,
      ');',
      '',
    );
  }
  const names = jobs.map((j) => quote(j.name)).join(', ');
  out.push(
    '-- Jobs no longer in the registry (only ones this file schedules: commands posting to /api/jobs/).',
    'select cron.unschedule(jobid) from cron.job',
    ` where command like '%/api/jobs/%' and jobname <> all (array[${names}]::text[]);`,
    '',
  );
  return out.join('\n');
}

export interface EmitArgs {
  check: boolean;
  stdout: boolean;
}

export function parseEmitArgs(argv: string[]): EmitArgs {
  const a: EmitArgs = { check: false, stdout: false };
  for (const arg of argv) {
    if (arg === '--check') a.check = true;
    else if (arg === '--stdout') a.stdout = true;
    else
      throw new Error(
        `unknown argument '${arg}' (usage: pnpm jobs:emit-cron [--check] [--stdout])`,
      );
  }
  return a;
}

export async function main(argv: string[], projectDir = process.cwd()): Promise<number> {
  const args = parseEmitArgs(argv);
  const { registry } = await import('../src/jobs/registry');
  const sql = emitCronSql(validateRegistry(registry));
  if (args.stdout) {
    process.stdout.write(sql);
    return 0;
  }
  const file = path.join(projectDir, CRON_SQL_FILE);
  if (args.check) {
    const current = existsSync(file) ? readFileSync(file, 'utf8') : null;
    if (current === sql) {
      console.log(`${CRON_SQL_FILE} is up to date`);
      return 0;
    }
    console.error(
      `${CRON_SQL_FILE} is ${current === null ? 'missing' : 'out of date'}: run pnpm jobs:emit-cron`,
    );
    return 1;
  }
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, sql);
  const n = cronJobs(validateRegistry(registry)).length;
  console.log(`wrote ${CRON_SQL_FILE} (${n} job${n === 1 ? '' : 's'})`);
  return 0;
}

if (isMainModule(import.meta.url)) {
  main(process.argv.slice(2)).then(
    (code) => {
      process.exitCode = code;
    },
    (e: Error) => {
      console.error(`jobs:emit-cron: ${e.message}`);
      process.exitCode = 1;
    },
  );
}
